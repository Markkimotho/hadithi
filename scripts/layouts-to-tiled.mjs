// Export authored layouts to Tiled JSON maps.
//
//   node scripts/layouts-to-tiled.mjs <tale> <source.mjs> [scene ...]
//
// <source.mjs> default-exports { sceneId: layout } in the compact layout
// format (see site/world/layout.js). The written site/maps/<tale>/*.json
// files are the source of truth from then on: open them in Tiled to edit.
// Only the scenes named (or all in the source) are written.
import { mkdir, writeFile, readFile } from "node:fs/promises";
import { pathToFileURL } from "node:url";
import { resolve } from "node:path";
import { parseLayout } from "../site/world/layout.js";

const [tale, sourcePath, ...only] = process.argv.slice(2);
if (!tale || !sourcePath) throw new Error("usage: layouts-to-tiled.mjs <tale> <source.mjs> [scene ...]");
const tileset = JSON.parse(await readFile(new URL(`../site/art/${tale}/tiles.json`, import.meta.url), "utf8"));
const { default: source } = await import(pathToFileURL(resolve(sourcePath)).href);
const root = new URL(`../site/maps/${tale}/`, import.meta.url);
const tileGid = new Map(tileset.tiles.map((tile, index) => [tile.glyph, index + 1]));
const properties = (entries) =>
  Object.entries(entries)
    .filter(([, value]) => value != null)
    .map(([name, value]) => ({
      name,
      type: typeof value === "number" ? "float" : typeof value === "boolean" ? "bool" : "string",
      value: typeof value === "string" || Array.isArray(value) || typeof value === "object" ? JSON.stringify(value) : value,
    }));
const point = ([x, y]) => ({ x: (x + 0.5) * 32, y: (y + 0.5) * 32, width: 0, height: 0, point: true });

await mkdir(root, { recursive: true });
let written = 0;
for (const [scene, raw] of Object.entries(source)) {
  if (only.length && !only.includes(scene)) continue;
  const base = raw.shares ? source[raw.shares] : null;
  const layout = parseLayout(base ? { ...raw, ground: base.ground, props: [], people: [] } : raw, `${tale}/${scene}`);
  const objects = [];
  let id = 1;
  for (const [from, at] of Object.entries(layout.spawn)) objects.push({ id: id++, name: from, type: "spawn", ...point(at) });
  for (const spot of layout.spots)
    objects.push({ id: id++, name: spot.id, type: "hotspot", ...point(spot.at), properties: properties({ actions: spot.actions, label: spot.name }) });
  for (const [action, cells] of Object.entries(layout.exits)) for (const at of cells) objects.push({ id: id++, name: action, type: "exit", ...point(at) });
  const packaged = (kind, list) =>
    list.map((item) => ({
      id: id++,
      name: item.id ?? item.kind ?? kind,
      type: kind,
      ...point(item.at),
      width: (item.w ?? 1) * 32,
      height: (item.h ?? 1) * 32,
      properties: properties(Object.fromEntries(Object.entries(item).filter(([key]) => key !== "at"))),
    }));
  objects.push(...packaged("prop", layout.props), ...packaged("person", layout.people));
  for (const flow of layout.flows)
    objects.push({ id: id++, name: flow.name ?? "current", type: "flow", x: flow.rect[0] * 32, y: flow.rect[1] * 32, width: flow.rect[2] * 32, height: flow.rect[3] * 32, properties: properties({ force: flow.force }) });
  const { width, height } = layout;
  const map = {
    type: "map", version: "1.10", tiledversion: "1.10.2", orientation: "orthogonal", renderorder: "right-down",
    width, height, tilewidth: 32, tileheight: 32, infinite: false,
    layers: [
      { id: 1, name: "ground", type: "tilelayer", width, height, opacity: 1, visible: true, data: layout.grid.flatMap((row) => row.map((glyph) => tileGid.get(glyph) ?? tileGid.get(" "))), x: 0, y: 0 },
      { id: 2, name: "objects", type: "objectgroup", draworder: "topdown", opacity: 1, visible: true, objects },
    ],
    tilesets: [
      {
        firstgid: 1, name: `${tale[0].toUpperCase()}${tale.slice(1)}Terrain`, tilewidth: 32, tileheight: 32,
        tilecount: tileset.tiles.length, columns: tileset.columns,
        image: `../../art/${tale}/tiles.svg`, imagewidth: tileset.columns * 32, imageheight: tileset.rows * 32,
        tiles: tileset.tiles.map((tile, index) => ({ id: index, properties: [{ name: "glyph", type: "string", value: tile.glyph }] })),
      },
    ],
    properties: properties({ shares: raw.shares, menu: layout.menu.length ? layout.menu : [], wind: layout.wind ?? [0, 0], light: raw.light }),
  };
  await writeFile(new URL(`${scene}.json`, root), `${JSON.stringify(map, null, 2)}\n`);
  written++;
}
// The index the world imports: every map in the folder.
const { readdir } = await import("node:fs/promises");
const scenes = (await readdir(root)).filter((f) => f.endsWith(".json")).map((f) => f.slice(0, -5)).sort();
const ident = (id) => `m_${id.replace(/\W/g, "_")}`;
await writeFile(
  new URL("index.js", root),
  [
    `// Generated by scripts/layouts-to-tiled.mjs. Every ${tale} map, by scene.`,
    ...scenes.map((id) => `import ${ident(id)} from "./${id}.json" with { type: "json" };`),
    "",
    `export default { ${scenes.map((id) => `${JSON.stringify(id)}: ${ident(id)}`).join(", ")} };`,
    "",
  ].join("\n"),
);
console.log(`Exported ${written} ${tale} maps to site/maps/${tale}/`);
